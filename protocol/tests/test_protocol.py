def setup_world(count=2, vehicle_class="car"):
    ledger = MockLedger()
    ledger.set_policy("road_access", {"car", "emergency"})
    pseudonyms = create_pseudonyms(count, 1, vehicle_class)
    register_pseudonyms(pseudonyms, ledger, time.time() + 600)
    sk1, pk1 = keygen()
    sk2, pk2 = keygen()
    trusted = {"RSU-1": pk1, "RSU-2": pk2}
    rsu1 = RSU("RSU-1", ledger, sk1, pk1, trusted_rsu_keys=trusted)
    rsu2 = RSU("RSU-2", ledger, sk2, pk2, trusted_rsu_keys=trusted)
    vehicle = Vehicle(pseudonyms, vehicle_class, trusted_rsu_keys=trusted)
    return ledger, pseudonyms, rsu1, rsu2, vehicle, pk1, pk2


def auth(ledger=None, pseudonyms=None, rsu=None, vehicle=None, service="road_access"):
    beacon = rsu.beacon()
    req = vehicle.make_auth_request(beacon, service)
    return beacon, req, rsu.authenticate(req)


def test_schnorr_proof_and_context_binding():
    sk, pk = keygen()
    ctx = b"rsu|nonce|service"
    proof = prove(sk, ctx)
    assert verify(pk, proof, ctx)
    assert not verify(pk, proof, b"changed-context")


def test_schnorr_signature_tampering():
    sk, pk = keygen()
    sig = schnorr_sign(sk, b"message")
    assert schnorr_verify(pk, b"message", sig)
    assert not schnorr_verify(pk, b"changed", sig)


def test_merkle_membership():
    leaves = [b"a", b"b", b"c"]
    tree = MerkleTree(leaves)
    for i, leaf in enumerate(leaves):
        assert verify_merkle(leaf, tree.proof(i), tree.root)
    assert not verify_merkle(b"not-a-leaf", tree.proof(0), tree.root)


