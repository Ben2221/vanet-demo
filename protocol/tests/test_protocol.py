def test_commitment_pool_and_precomputed_proof():
    """Requirement: Pool of precomputed commitments (g^r computed while idle), each r used exactly once.
    Also proves the mathematical hazard of commitment reuse."""
    from protocol.crypto import CommitmentPool, N, _base_mul, _hash_scalar
    pool = CommitmentPool(initial_size=5)
    assert len(pool) == 5
    comm1 = pool.pop()
    comm2 = pool.pop()
    assert comm1.r != comm2.r
    assert len(pool) == 3

    # Use precomputed commitment in proof
    sk, pk = keygen()
    ctx1 = b"context-1"
    proof1 = prove(sk, ctx1, commitment=comm1)
    assert verify(pk, proof1, ctx1)

    # Mathematical demonstration: if the same commitment r were reused for two different challenges,
    # the private key x is immediately extractable by an attacker:
    # s1 = r + c1*x, s2 = r + c2*x => s1 - s2 = (c1 - c2)*x => x = (s1 - s2) / (c1 - c2) mod N
    ctx2 = b"context-2"
    reused_comm = pool.pop()
    proof_a = prove(sk, ctx1, commitment=reused_comm)
    proof_b = prove(sk, ctx2, commitment=reused_comm)
    c1 = _hash_scalar(b"SCHNORR-FS-v1", bytes.fromhex(proof_a.commitment), pk, ctx1)
    c2 = _hash_scalar(b"SCHNORR-FS-v1", bytes.fromhex(proof_b.commitment), pk, ctx2)
    s1 = int.from_bytes(bytes.fromhex(proof_a.response), "big")
    s2 = int.from_bytes(bytes.fromhex(proof_b.response), "big")
    recovered_sk = ((s1 - s2) * pow(c1 - c2, -1, N)) % N
    assert recovered_sk == sk, "reusing r leaks the private key; pool guarantees single-use"


def test_preauth_over_rsu_backbone():
    """Requirement: Pre-authorization over the RSU backbone. An RSU sends a signed note to its
    neighbours so a handover works before the ledger commit lands."""
    ledger, ps, rsu1, rsu2, vehicle, pk1, _ = setup_world(count=1)
    _, _, auth_res = auth(ledger, ps, rsu1, vehicle)
    assert auth_res["ok"]
    ticket = auth_res["ticket"]
    assert vehicle.accept_ticket(ticket, pk1)

    # RSU 1 sends signed PREAUTH over backbone to RSU 2
    preauth_bytes = rsu1.preauthorize_neighbour("RSU-2", ticket)
    rec_res = rsu2.receive_preauth(preauth_bytes)
    assert rec_res["ok"] and rec_res["reason"] == "preauth_accepted"

    # Simulate ledger not having the auth record yet (e.g. Fabric commit latency)
    ledger.auth_records.clear()
    assert ledger.get_auth(ps[0].pid) is None

    # Vehicle performs handover at RSU 2 - should succeed via preauth cache!
    req = vehicle.make_handover_request("RSU-2")
    handover_res = rsu2.handover(req)
    assert handover_res["ok"] and handover_res["reason"] == "handover_accepted"


