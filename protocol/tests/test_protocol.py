def test_pure_python_complete_end_to_end_flow():
    """Requirement (PDF Pages 16, 20-21):
    A pure-Python run shows registration, authentication, handover, revocation and identity reveal working end to end:
    1. TA registers vehicles, publishes Merkle root to ledger (no real identity on ledger).
    2. Vehicle authenticates with RSU 1 using Schnorr ZKP, gets signed ticket.
    3. Vehicle uses make-before-break handover / backbone PREAUTH to switch to RSU 2.
    4. Vehicle begins sending misbehaving BSMs.
    5. Misbehaviour detector flags messages; 2 RSUs report it to ledger.
    6. Ledger auto-revokes the malicious pseudonym. Subsequent auths and BSMs rejected.
    7. Trace request opened on ledger, RSUs approve up to threshold (2f+1 = 3).
    8. Identity escrow shares gathered from RSUs, AES-GCM decrypts real identity (VIN, owner).
    9. TA revokes all of the vehicle's pseudonyms on the ledger.
    """
    from protocol.escrow import ThresholdIdentityEscrow, RSUEscrowAgent

    # 1. Setup World & Ledger
    ledger = MockLedger()
    ledger.set_policy("road_access", {"car", "emergency"})
    ledger.trace_threshold = 3

    sk1, pk1 = keygen()
    sk2, pk2 = keygen()
    trusted = {"RSU-1": pk1, "RSU-2": pk2}

    class SimpleDetector:
        def check(self, bsm_payload, history):
            speed = bsm_payload.get("fields", {}).get("speed", 0.0)
            return (speed > 50.0, {"flag": "excessive_speed"})

    detector = SimpleDetector()
    rsu1 = RSU("RSU-1", ledger, sk1, pk1, trusted_rsu_keys=trusted, detector=detector, detector_k=1)
    rsu2 = RSU("RSU-2", ledger, sk2, pk2, trusted_rsu_keys=trusted, detector=detector, detector_k=1)

    # 2. Vehicle Registration & Threshold Escrow
    pseudonyms = create_pseudonyms(3, epoch=1, vehicle_class="car")
    register_pseudonyms(pseudonyms, ledger, time.time() + 3600)

    # Verify no real identity on ledger
    assert ledger.get_root(1) is not None
    assert "Alice" not in str(ledger.root_by_epoch)

    escrow = ThresholdIdentityEscrow(threshold=3, rsu_orgs=["RSU-1", "RSU-2", "RSU-3", "RSU-4", "RSU-5"])
    real_identity = {
        "vin": "1HGCR2F8XHA112233",
        "owner": "Alice Smith",
        "pids": [p.pid for p in pseudonyms]
    }
    escrow_record, shares = escrow.escrow_vehicle_identity(real_identity)
    agents = {rsu_id: RSUEscrowAgent(rsu_id, share, ledger) for rsu_id, share in shares.items()}

    vehicle = Vehicle(pseudonyms, vehicle_class="car", trusted_rsu_keys=trusted)

    # 3. Authentication at RSU 1
    beacon1 = rsu1.beacon()
    auth_req = vehicle.make_auth_request(beacon1, "road_access")
    auth_res = rsu1.authenticate(auth_req)
    assert auth_res["ok"], auth_res
    assert vehicle.accept_ticket(auth_res["ticket"], pk1)

    # 4. Backbone PREAUTH & Make-before-break Handover to RSU 2
    preauth_bytes = rsu1.preauthorize_neighbour("RSU-2", auth_res["ticket"])
    assert rsu2.receive_preauth(preauth_bytes)["ok"]
    handover_req = vehicle.make_before_break_handover("RSU-2", next_rsu_beacon=rsu2.beacon())
    assert rsu2.handover(handover_req)["ok"]

    # 5. Legitimate BSM
    valid_bsm = vehicle.make_bsm(speed=30.0, x=100.0, y=200.0)
    bsm_res = rsu2.verify_bsm(valid_bsm)
    assert bsm_res["ok"] and not bsm_res["flagged"]

    # 6. Misbehaving BSMs detected and reported by 2 RSUs
    malicious_bsm1 = vehicle.make_bsm(speed=95.0, x=100.0, y=200.0)
    m_res1 = rsu1.verify_bsm(malicious_bsm1)
    assert m_res1["ok"] and m_res1["flagged"]

    malicious_bsm2 = vehicle.make_bsm(speed=110.0, x=120.0, y=210.0)
    m_res2 = rsu2.verify_bsm(malicious_bsm2)
    assert m_res2["ok"] and m_res2["flagged"]

    # 7. Automatic Revocation on Ledger
    active_pid = vehicle.current.pid
    assert ledger.is_revoked(active_pid)

    # Subsequent auth rejected
    assert not rsu1.authenticate(vehicle.make_auth_request(rsu1.beacon(), "road_access"))["ok"]

    # 8. Trace Request & Threshold Identity Reveal
    ledger.request_trace("trace-case-42", active_pid, "reckless driving speed > 100 m/s")
    ledger.approve_trace("trace-case-42", "RSU-1")
    ledger.approve_trace("trace-case-42", "RSU-2")
    ledger.approve_trace("trace-case-42", "RSU-3")
    assert ledger.is_trace_approved("trace-case-42")

    collected_shares = [
        agents["RSU-1"].release_share("trace-case-42"),
        agents["RSU-2"].release_share("trace-case-42"),
        agents["RSU-3"].release_share("trace-case-42")
    ]
    unmasked = escrow.unmask(escrow_record, collected_shares)
    assert unmasked["owner"] == "Alice Smith"
    assert unmasked["vin"] == "1HGCR2F8XHA112233"

    # 9. TA revokes all pseudonyms of this vehicle
    ledger.revoke(unmasked["pids"], reason="trace_unmasked")
    for p in pseudonyms:
        assert ledger.is_revoked(p.pid)
