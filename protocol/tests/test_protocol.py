    raw_p = p.to_bytes()
    p2 = PreauthMessage.from_bytes(raw_p)
    assert p2.source_rsu == "RSU-1" and p2.target_rsu == "RSU-2"

    # 6. BSM
    bsm = BsmMessage(payload={"pid": "pid123", "speed": 25.0}, public_key="02"+"d"*64)
    raw_bsm = bsm.to_bytes()
    bsm2 = BsmMessage.from_bytes(raw_bsm)
    assert bsm2.payload["speed"] == 25.0


