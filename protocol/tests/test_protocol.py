def test_detector_hook_and_auto_revocation():
    """Requirement: Run misbehaviour detector on received safety messages and send reports.
    Two reports from different RSUs revoke a pseudonym automatically (K = 2)."""
    # Simple rule-based detector for testing
    class SpeedDetector:
        def check(self, bsm_payload, history):
            speed = bsm_payload.get("fields", {}).get("speed", 0.0)
            return (speed > 40.0, {"anomaly": "excessive_speed" if speed > 40.0 else "none"})

    detector = SpeedDetector()
    ledger, ps, rsu1, rsu2, vehicle, pk1, pk2 = setup_world(count=1)
    rsu1.detector = detector
    rsu1.detector_k = 2  # report after 2 flagged messages
    rsu2.detector = detector
    rsu2.detector_k = 2

    _, _, auth_res = auth(ledger, ps, rsu1, vehicle)
    assert auth_res["ok"] and vehicle.accept_ticket(auth_res["ticket"], pk1)

    pid = ps[0].pid
    assert not ledger.is_revoked(pid)

    # Vehicle sends 2 anomalous BSMs to RSU-1 (speed = 65 m/s)
    bsm1 = vehicle.make_bsm(speed=65.0, x=10.0, y=10.0)
    bsm2 = vehicle.make_bsm(speed=70.0, x=20.0, y=20.0)
    rsu1.verify_bsm(bsm1)
    rsu1.verify_bsm(bsm2)

    # RSU 1 reported, but 1 report is not enough for auto-revocation (needs K=2 RSUs)
    assert not ledger.is_revoked(pid)

    # Vehicle sends 2 anomalous BSMs to RSU-2
    rsu2.preauth_cache[pid] = auth_res["ticket"]["payload"]
    bsm3 = vehicle.make_bsm(speed=80.0, x=30.0, y=30.0)
    bsm4 = vehicle.make_bsm(speed=85.0, x=40.0, y=40.0)
    rsu2.verify_bsm(bsm3)
    rsu2.verify_bsm(bsm4)

    # Now both RSU-1 and RSU-2 have reported -> auto-revocation triggered!
    assert ledger.is_revoked(pid)

    # Next authentication with this pseudonym must fail with "revoked"
    beacon1 = rsu1.beacon()
    try:
        auth_req = vehicle.make_auth_request(beacon1, "road_access")
        auth_retry = rsu1.authenticate(auth_req)
        assert not auth_retry["ok"] and auth_retry["reason"] == "revoked"
    except Exception:
        pass

    # Subsequent BSMs from revoked pseudonym are rejected
    bsm5 = vehicle.make_bsm(speed=20.0, x=50.0, y=50.0)
    res_bsm = rsu1.verify_bsm(bsm5)
    assert not res_bsm["ok"] and res_bsm["reason"] == "expired_or_revoked"


def test_threshold_identity_escrow_and_reveal():
    """Requirement: Threshold identity escrow. TA encrypts vehicle identity (AES-GCM) and splits key
    among RSU organizations (Shamir secret sharing). RSUs release shares only if GetTrace is approved.
    TA alone cannot unmask anyone. Trace approved at threshold -> real identity unmasked and pseudonyms revoked."""
    from protocol.escrow import ThresholdIdentityEscrow, RSUEscrowAgent

    ledger = MockLedger()
    ledger.trace_threshold = 3  # threshold of 3 RSUs
    escrow = ThresholdIdentityEscrow(threshold=3, rsu_orgs=["RSU-1", "RSU-2", "RSU-3", "RSU-4", "RSU-5"])

    real_identity = {
        "vin": "1HGCR2F8XHA999999",
        "owner": "Charlie Brown",
        "real_id": "DRIVER-ID-8844",
        "pids": ["pid-alpha", "pid-beta", "pid-gamma"]
    }

    # TA creates encrypted escrow record and distributes shares to RSU agents
    record, shares = escrow.escrow_vehicle_identity(real_identity)
    agents = {rsu_id: RSUEscrowAgent(rsu_id, share, ledger) for rsu_id, share in shares.items()}

    # Check 1: RSU agents refuse to release share without approved trace
    try:
        agents["RSU-1"].release_share("trace-req-001")
        assert False, "should fail without trace approval"
    except PermissionError as exc:
        assert "not approved" in str(exc)

    # Check 2: Open trace request on ledger
    ledger.request_trace("trace-req-001", "pid-alpha", "suspected hit and run")
    assert not ledger.is_trace_approved("trace-req-001")

    # Check 3: Add approvals up to threshold
    ledger.approve_trace("trace-req-001", "RSU-1")
    ledger.approve_trace("trace-req-001", "RSU-2")
    assert not ledger.is_trace_approved("trace-req-001")  # 2 < 3

    # Still rejected with 2 approvals
    try:
        agents["RSU-1"].release_share("trace-req-001")
        assert False, "should fail with only 2 approvals"
    except PermissionError:
        pass

    # 3rd approval reaches threshold
    ledger.approve_trace("trace-req-001", "RSU-3")
    assert ledger.is_trace_approved("trace-req-001")

    # Check 4: Approved RSUs release shares
    share1 = agents["RSU-1"].release_share("trace-req-001")
    share2 = agents["RSU-2"].release_share("trace-req-001")
    share3 = agents["RSU-3"].release_share("trace-req-001")

    # Check 5: 2 shares are insufficient to decrypt
    try:
        escrow.unmask(record, [share1, share2])
        assert False, "2 shares must not decrypt threshold 3 record"
    except ValueError as exc:
        assert "insufficient shares" in str(exc).lower()

    # Check 6: 3 shares successfully unmask real identity
    unmasked = escrow.unmask(record, [share1, share2, share3])
    assert unmasked["vin"] == real_identity["vin"]
    assert unmasked["owner"] == real_identity["owner"]
    assert unmasked["pids"] == real_identity["pids"]

    # Check 7: TA revokes all of vehicle's pseudonyms on ledger
    ledger.revoke(unmasked["pids"], reason="trace_unmasked")
    for pid in unmasked["pids"]:
        assert ledger.is_revoked(pid)


def test_typed_message_classes_and_sizes():
    """Requirement: Message types (BEACON, AUTH_REQ, AUTH_RESP, HANDOVER_REQ, PREAUTH, BSM),
    each with to_bytes() and from_bytes() and a documented size in bytes."""
    from protocol.messages import (
        BeaconMessage, AuthReqMessage, AuthRespMessage,
        HandoverReqMessage, PreauthMessage, BsmMessage
    )

    # 1. BEACON
    b = BeaconMessage(rsu_id="RSU-1", nonce="a"*32, timestamp=100.0, public_key="02"+"b"*64)
    raw_b = b.to_bytes()
    b2 = BeaconMessage.from_bytes(raw_b)
    assert b2.rsu_id == "RSU-1"
    assert 100 < len(raw_b) < 600

    # 2. AUTH_REQ
    req = AuthReqMessage(pid="pid123", public_key="02"+"c"*64, epoch=1, service="road_access", vehicle_class="car")
    raw_req = req.to_bytes()
    req2 = AuthReqMessage.from_bytes(raw_req)
    assert req2.pid == "pid123"
    assert 100 < len(raw_req) < 800

    # 3. AUTH_RESP
    resp = AuthRespMessage(ok=True, ticket={"payload": {"pid": "pid123"}}, reason="authenticated")
    raw_resp = resp.to_bytes()
    resp2 = AuthRespMessage.from_bytes(raw_resp)
    assert resp2.ok and resp2.reason == "authenticated"

    # 4. HANDOVER_REQ
    h = HandoverReqMessage(ticket={"payload": {"pid": "pid123"}}, next_rsu_id="RSU-2")
    raw_h = h.to_bytes()
    h2 = HandoverReqMessage.from_bytes(raw_h)
    assert h2.next_rsu_id == "RSU-2"

